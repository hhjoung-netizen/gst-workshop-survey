name = st.text_input("이름")
department = st.text_input("부서", value="품질혁신팀")
position = st.selectbox(
    "직급",
    ["사원", "대리", "과장", "차장", "부장", "기타"]
)

responses = {}

st.header("설문 문항")

for idx, q in enumerate(questions, start=1):
    answer = st.radio(
        f"Q{idx}. {q['question']}",
        list(q["options"].keys()),
        key=f"q_{idx}"
    )

    responses[f"Q{idx}"] = answer

# =========================
# 결과 계산
# =========================

if st.button("설문 제출 및 결과 보기"):

    score = {
        "분석형": 0,
        "실행형": 0,
        "조율형": 0,
        "관리형": 0
    }

    for idx, q in enumerate(questions, start=1):
        selected = responses[f"Q{idx}"]
        result_type = q["options"][selected]
        score[result_type] += 1

    max_score = max(score.values())

    top_types = [k for k, v in score.items() if v == max_score]

    if len(top_types) == 1:
        final_type = top_types[0]
    else:
        final_type = " + ".join(top_types)

    # 대표 유형 기준으로 해석 사용
    guide_type = top_types[0]

    guide = TYPE_GUIDE[guide_type]

    result_data = {
        "제출시간": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "이름": name,
        "부서": department,
        "직급": position,
        "대표 유형": final_type,
        "분석형 점수": score["분석형"],
        "실행형 점수": score["실행형"],
        "조율형 점수": score["조율형"],
        "관리형 점수": score["관리형"],
        "핵심 특징": guide["핵심 특징"],
        "강점": guide["강점"],
        "주의점": guide["주의점"],
        "추천 역할": guide["추천 역할"],
        "협업 팁": guide["협업 팁"],
        "스트레스 요인": guide["스트레스 요인"]
    }

    for idx, q in enumerate(questions, start=1):
        result_data[f"Q{idx}"] = responses[f"Q{idx}"]

    result_df = pd.DataFrame([result_data])

    file_name = "survey_results.csv"

    if os.path.exists(file_name):
        result_df.to_csv(
            file_name,
            mode="a",
            header=False,
            index=False,
            encoding="utf-8-sig"
        )
    else:
        result_df.to_csv(
            file_name,
            index=False,
            encoding="utf-8-sig"
        )

    # =========================
    # 결과 출력
    # =========================

    st.success("설문이 정상 제출되었습니다.")

    st.header("📊 분석 결과")

    st.subheader(f"대표 유형: {final_type}")

    col1, col2, col3, col4 = st.columns(4)

    col1.metric("분석형", score["분석형"])
    col2.metric("실행형", score["실행형"])
    col3.metric("조율형", score["조율형"])
    col4.metric("관리형", score["관리형"])

    st.markdown("---")

    st.subheader("핵심 특징")
    st.write(guide["핵심 특징"])

    st.subheader("강점")
    st.write(guide["강점"])

    st.subheader("주의점")
    st.write(guide["주의점"])

    st.subheader("추천 역할")
    st.write(guide["추천 역할"])

    st.subheader("협업 팁")
    st.write(guide["협업 팁"])

    st.subheader("스트레스 요인")
    st.write(guide["스트레스 요인"])

    st.markdown("---")

    st.info("모든 설문 결과는 survey_results.csv 파일로 자동 저장됩니다.")

